export function getCmsMessages(locale: Locale) {
  const copy = cmsMessages[locale];
  return {
    ...copy,
    formatBytes: (value: number) => `${value.toLocaleString(locale)} B`,
    formatDimensions: (width: number, height: number) =>
      `${width.toLocaleString(locale)} × ${height.toLocaleString(locale)}`,
    relationship: {
      ...copy.relationship,
      sorting: {
        listLabel: copy.sort.list,
        roleDescription: copy.sort.roleDescription,
        invalidItemsLabel: copy.sort.invalid,
        instructions: copy.sort.instructions,
        handleLabel: (label: string) => `${copy.sort.handle} ${label}`,
        start: (label: string) => `${copy.sort.start} ${label}`,
        move: (label: string, position: number, total: number) =>
          `${label}: ${copy.sort.move} ${position}/${total}`,
        end: (label: string, position: number, total: number) =>
          `${copy.sort.end} ${label}: ${position}/${total}`,
        cancel: (label: string) => `${copy.sort.cancel} ${label}`,
      },
    },
  };
}

export type CmsCopy = ReturnType<typeof getCmsMessages>;
