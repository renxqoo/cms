export type WorkMessages = (typeof workMessages)['en' | 'zh'];

export function workStatus(status: string, t: WorkMessages) {
  if (status === 'cancelled') return t.cancelledStatus;
  if (status === 'expired') return t.expiredStatus;
  const known: Readonly<Record<string, string>> = {
    queued: t.queued,
    running: t.running,
    succeeded: t.succeeded,
    partial: t.partial,
    failed: t.failed,
    pending: t.pending,
    uploading: t.uploading,
    processing: t.processing,
    ready: t.ready,
    consumed: t.consumed,
  };
  return Object.hasOwn(known, status) ? (known[status] ?? status) : status;
}
